"""The `cancho-binding` generator (gen/cancho-binding/) — typed
driver-side declarations for a contract.

Output contract: `spec/generators/README.md` §3. A `.cancho`
file exposing accessors for register fields, interrupt
capability groups, and DMA buffer fields — accessors only,
never driver logic (§3.3).

The accessor palette (the landed form of the §3.1 sketch):

- One `capability` block per interrupt:
  `capability <PascalBlock><PascalIntr>` with
  `arm()` when an `enable` linkage is declared,
  `status() -> bool` when a `status` linkage is declared,
  `clear()` when a `clear` linkage is declared.
- Register field accessors, named `<reg>_<field>` in lower
  snake case, typed by the field:
  * width 1 → `bool`.
  * an `enum` → a module-level `enum <PascalField>` declaration
    (labels verbatim; two same-named fields with different
    label sets refuse rather than collide).
  * otherwise → `u32` (the bus-width grain).
  * boolean getters are bare (`fn ctrl_enable() -> bool;`);
    typed getters carry `_get()` (the §3.1 sketch's
    `parity_get()`); setters carry `_set(v: T)`.
- Which accessors exist is the register's job:
  `RO`/`RC` → getter only; `WO` → setter only; `W1C`/`W0C` →
  `_clear()`; `W1S`/`W0S` → `_set()`; `RW` → getter + setter.
- DMA buffer fields follow §3.2's enforcement rule literally:
  a `DEVICE`-owned field gets a getter and **no setter**; a
  `CPU`-owned field gets both. Sizes follow the c-header's
  convention (explicit `size`, else 4 — the packed-struct
  grain both artifacts share), mapped to `u8`/`u16`/`u32`/`u64`.
  Any other size refuses (`generator-unimplemented`) — the same
  refusal the c-header now raises for the same input, so the
  two artifacts cannot disagree silently.

Stable IDs (§1 rule 3) appear as `//` comments on every entity
the file touches. The generator reads the IR only, and is a
deterministic function of it.
"""

from __future__ import annotations

import pathlib as _pathlib
import re
import sys as _sys
from typing import Any

# Same loading discipline as gen/devicetree (module-by-path; gen/
# must be importable for the shared refusal class).
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[1]))
from common import GeneratorUnimplemented


def _snake(name: str) -> str:
    s1 = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s2 = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s1)
    return s2.lower()


def _pascal(name: str) -> str:
    snake = _snake(name)
    return "".join(part[:1].upper() + part[1:] for part in snake.split("_"))


def _hex(v: int) -> str:
    return f"0x{v:X}"


def _field_type(field: dict[str, Any]) -> tuple[str, str | None]:
    """(type name, enum-decl-name-or-None) for a register field."""
    width = int(field["msb"]) - int(field["lsb"]) + 1
    enum = field.get("enum")
    if enum:
        return _pascal(field["name"]), _pascal(field["name"])
    return ("bool" if width == 1 else "u32"), None


def _dma_type(size: int) -> str:
    sizes = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}
    if size not in sizes:
        raise GeneratorUnimplemented(
            f"DMA field size {size} has no u8/u16/u32/u64 mapping; refusing "
            "(the c-header refuses it too — the two artifacts must agree)")
    return sizes[size]


_ACCESSORS: dict[str, tuple[str, ...]] = {
    # kind → available ops
    "RO":  ("get",),
    "RC":  ("get",),
    "WO":  ("set",),
    "RW":  ("get", "set"),
    "W1C": ("clear",),
    "W0C": ("clear",),
    "W1S": ("set",),
    "W0S": ("set",),
}


def generate(ir: dict[str, Any], source_path: str = "<memory>") -> str:
    block = ir["block"]
    block_name = block["name"]
    snake_block = _snake(block_name)
    bus_width = int(block.get("bus_width", 32))
    base = int(str(block["base_address"]), 16)

    enum_decls: list[tuple[str, list[str]]] = []
    seen_enum: dict[str, list[str]] = {}

    lines: list[str] = [
        f"// Generated by cancho-hdl from {source_path}. Do not edit.",
        "",
        f"module {snake_block} {{",
        f"    foreign block {block_name} @ {_hex(base)} : u{bus_width};",
        "",
    ]

    for reg in block.get("registers", []) or []:
        reg_name = reg["name"]
        reg_snake = _snake(reg_name)
        kind = reg.get("kind", "RW")
        ops = _ACCESSORS.get(kind)
        if ops is None:  # pragma: no cover — checker rejects unknown kinds first
            raise GeneratorUnimplemented(
                f"register kind {kind!r} has no cancho accessor mapping")
        for field in reg.get("fields", []) or []:
            f_name = field["name"]
            f_snake = _snake(f_name)
            lines.append(
                f"    // chw:{block_name}.register.{reg_name}.field.{f_name}")
            t, enum_name = _field_type(field)
            if enum_name is not None:
                labels = list(field["enum"].keys())
                prev = seen_enum.get(enum_name)
                if prev is not None and prev != labels:
                    raise GeneratorUnimplemented(
                        f"two enum fields named {f_name!r} carry different "
                        f"label sets; refusing to collide the type {enum_name}")
                seen_enum[enum_name] = labels
                if enum_name not in [n for n, _ in enum_decls]:
                    enum_decls.append((enum_name, labels))
            if "get" in ops:
                getter = f"{reg_snake}_{f_snake}() -> {t}"
                if t != "bool":
                    getter = f"{reg_snake}_{f_snake}_get() -> {t}"
                lines.append(f"    fn {getter};")
            if "clear" in ops:
                lines.append(f"    fn {reg_snake}_{f_snake}_clear();")
            if "set" in ops:
                lines.append(f"    fn {reg_snake}_{f_snake}_set(v: {t});")

    interrupts = block.get("interrupts", []) or []
    if interrupts:
        lines.append("")
    for intr in interrupts:
        iname = intr["name"]
        iname_snake = _snake(iname)
        lines.append(f"    // chw:{block_name}.interrupt.{iname}")
        lines.append(f"    capability {_pascal(block_name)}{_pascal(iname)}")
        if "enable" in intr:
            lines.append(f"    fn {iname_snake}_arm();")
        if "status" in intr:
            lines.append(f"    fn {iname_snake}_status() -> bool;")
        if "clear" in intr:
            lines.append(f"    fn {iname_snake}_clear();")

    dma_buffers = ir.get("dma_buffers", []) or []
    for buf in dma_buffers:
        buf_name = buf["name"]
        lines.append("")
        lines.append(f"    // chw:{block_name}.dma.{buf_name}")
        lines.append(f"    buffer {buf_name} {{")
        for f in buf.get("fields", []) or []:
            f_name = f["name"]
            size = int(f.get("size", 4))
            t = _dma_type(size)
            lines.append(
                f"        // chw:{block_name}.dma.{buf_name}.field.{f_name}")
            lines.append(f"        fn {_snake(f_name)}() -> {t};")
            if f.get("owner", "CPU") != "DEVICE":
                # §3.2: DEVICE-owned fields have no setter — the type
                # system is the enforcement, there is nothing to check
                # at runtime.
                lines.append(f"        fn {_snake(f_name)}_set(v: {t});")
            else:
                lines.append(
                    f"        // no setter: DEVICE-owned (the field is the "
                    f"device's to write)")
        lines.append("    }")

    lines.append("}")

    for enum_name, labels in enum_decls:
        lines.append("")
        lines.append(f"enum {enum_name} {{ {', '.join(labels)} }}")

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import argparse
    import json
    import sys

    ap = argparse.ArgumentParser(prog="gen/cancho-binding")
    ap.add_argument("file")
    args = ap.parse_args()
    ir = json.loads(open(args.file).read())
    sys.stdout.write(generate(ir, source_path=args.file))

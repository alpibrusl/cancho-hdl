"""The `devicetree` generator (gen/devicetree/) — a DTSI fragment.

Output contract: `spec/generators/README.md` §4. The fragment
describes the block for Linux / Zephyr / RTOS device-tree
consumers. It reads the contract IR only, is a deterministic
function of it, and carries the stable IDs as comments
(`chw:<block>.interrupt.<name>`) — the one link from the
generated fragment back to the contract.

What the fragment contains (§4.1/§4.2):

- One node per block, named `snake(<block>)@<base>` with the
  same snake as label.
- `compatible = "cancho,<snake>-v<major>"` — the schema-version
  major of the contract that produced it.
- `reg = <base size>` where `size = max_register_offset +
  bus_width/8` (§4.2's formula). A node that does not fit one
  32-bit address cell (base ≥ 2^32) is refused
  (`generator-unimplemented`) — never silently widened.
- `interrupt-parent`/`interrupts` only when the block declares
  interrupts, in declaration order, one flag cell per the §4.1
  sketch. The flag encoding is the sketch's placeholder; the
  real encoding belongs to the board's intc binding.
- `bus-width` as a plain informational property.

The fragment is **block-level only**: it does not encode clocks,
resets, pinctrl, per-register nodes, or DMA buffer bindings
(§4.3 non-guarantees) — those are board-level concerns outside
the contract's scope.

Exit / refusal behavior is the generator contract (§1 rule 4/5):
refuse on missing features (`GeneratorUnimplemented`), raise
raw exceptions on a malformed IR the checker should have caught
(the dispatcher reports them as `internal`).
"""

from __future__ import annotations

import pathlib as _pathlib
import re
import sys as _sys
from typing import Any

# This module is loaded by module path (no package); importing the
# shared `common` module needs gen/ on sys.path in every entry point.
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[1]))
from common import GeneratorUnimplemented


_INDENT = "    "


def _snake(name: str) -> str:
    s1 = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s2 = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s1)
    return s2.lower()


def _hex(v: int) -> str:
    return f"0x{v:X}"


def generate(ir: dict[str, Any], source_path: str = "<memory>") -> str:
    block = ir["block"]
    name = block["name"]
    snake = _snake(name)
    dash = snake.replace("_", "-")
    bus_width = int(block.get("bus_width", 32))
    base = int(str(block["base_address"]), 16)

    version = str(ir.get("version", "0.1.0"))
    major = version.split(".")[0]

    registers = block.get("registers", []) or []
    if not registers:
        raise GeneratorUnimplemented(
            "devicetree fragment with zero registers: the reg range is "
            "undefined; declare at least one register")
    max_offset = max(int(str(r["offset"]), 16) for r in registers)
    range_size = max_offset + bus_width // 8

    if base > 0xFFFFFFFF:
        raise GeneratorUnimplemented(
            f"base_address {_hex(base)} does not fit a single 32-bit "
            "address cell (#address-cells = <1>); refusing, not widening")

    unit = f"{base:X}"
    len_indent = _INDENT * 2

    lines: list[str] = [
        f"/* Generated by cancho-hdl from {source_path}. Do not edit. */",
        "&soc {",
        f"{_INDENT}{snake}: {snake}@{unit} {{",
        f"{len_indent}/* chw:{name} */",
        f"{len_indent}compatible = \"cancho,{dash}-v{major}\";",
        f"{len_indent}reg = <{_hex(base)} {_hex(range_size)}>;",
    ]

    interrupts = block.get("interrupts", []) or []
    if interrupts:
        lines.append(f"{len_indent}interrupt-parent = <&intc>;")
        entries = []
        for intr in interrupts:
            num = int(intr["number"])
            entries.append(f"<{num} 4>")
        if len(entries) == 1:
            lines.append(f"{len_indent}interrupts = {entries[0]};")
        else:
            gap = " " * len("interrupts = ")
            lines.append(f"{len_indent}interrupts = {entries[0]},")
            for e in entries[1:-1]:
                lines.append(f"{len_indent}{gap}{e},")
            lines.append(f"{len_indent}{gap}{entries[-1]};")
        for intr in interrupts:
            num = int(intr["number"])
            lines.append(
                f"{len_indent}/* chw:{name}.interrupt.{intr['name']}, IRQ {num} */")

    lines += [
        f"{len_indent}#address-cells = <1>;",
        f"{len_indent}#size-cells = <1>;",
        f"{len_indent}bus-width = <{bus_width}>;",
        f"{_INDENT}}};",
        "};",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import argparse
    import json
    import sys

    ap = argparse.ArgumentParser(prog="gen/devicetree")
    ap.add_argument("file")
    args = ap.parse_args()
    ir = json.loads(open(args.file).read())
    sys.stdout.write(generate(ir, source_path=args.file))

"""Hardware replay of the behavioral corpus on the Tang Nano 20K, through the UART/AXI4-Lite bridge.

The same corpus (`tests/behavioral/scenarios.json`), the same oracle (the reference model) and the same op planning as the
simulated SystemVerilog roundtrip (`tests/behavioral/sv_behavior.py`); the module under test is the generated register block
running in the FPGA. Python here is a test oracle only.

  python3 tests/hardware/board_replay.py top CHW CONTRACT.chw > top.v     # top level for any contract, bridge + its register block
  python3 tests/hardware/board_replay.py run CHW [--port /dev/ttyUSB1] [--contract examples/uart-contract/uart.chw] [-v]

`run` needs the board loaded with the design `top` produced for that contract (build.sh-style flow, see docs/tang-nano-20k.md).

What differs from the simulated roundtrip, and is reported rather than hidden:
  * The host has no reset line. RESET (and the start of each scenario) is emulated: every RW register is written to its reset
    value and read back. Registers of other kinds are only ever changed by the device, and this design has no device logic.
    A scenario's emulated resets are counted as `emulated-reset`.
  * Ops with no bus port (D, DW, IP, ...), tainted reads, and model refusals are skipped exactly as in sv_behavior.py.
  * Byte-strobe writes are not in the bridge's protocol; the strobe directed checks are not run.
"""
from __future__ import annotations

import argparse, json, os, pathlib, re, select, subprocess, sys, termios, time

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests" / "behavioral"))
import sv_behavior as sv  # noqa: E402  (plan() and its oracle imports)
from sv_behavior import plan, load_contract, _field_mask  # noqa: E402


def top_source(chw: str, contract: str) -> str:
    gen = subprocess.run([chw, "generate", str(ROOT / contract), "--target", "systemverilog"], capture_output=True, text=True,
                         cwd=ROOT, check=True).stdout
    mod = re.search(r"^module (\w+) #\(", gen, re.M).group(1)
    outs = re.findall(r"output wire \[DATA_WIDTH-1:0\]\s+(reg_\w+_out)", gen)
    ins = re.findall(r"input  wire \[DATA_WIDTH-1:0\]\s+(reg_\w+_in)", gen)   # device-written registers: tied to 0 (no device logic in this top)
    wires = "\n".join(f"    wire [31:0] {o};" for o in outs)
    conns = ",\n        ".join([".clk(clk)", ".rst_n(rst_n)"] + [f".s_axi_{p}({p})" for p in (
        "awaddr awvalid awready wdata wstrb wvalid wready bresp bvalid bready araddr arvalid arready rdata rresp rvalid rready".split())]
        + [f".{i}(32'h0)" for i in ins] + [f".{o}({o})" for o in outs])
    led = f"~{outs[0]}[5:0]" if outs else "6'h3f"
    return f"""// Generated by tests/hardware/board_replay.py from {contract}: the UART bridge on the register block. LEDs show {outs[0] if outs else 'nothing'}[5:0].
`timescale 1ns/1ps
`default_nettype none
module top #(parameter CLKS_PER_BIT = 234) (input wire clk, input wire uart_rx, output wire uart_tx, output wire [5:0] led);
    reg [3:0] rst_cnt = 4'd0;
    wire rst_n = &rst_cnt;
    always @(posedge clk) if (!rst_n) rst_cnt <= rst_cnt + 4'd1;
    wire [31:0] awaddr, wdata, araddr, rdata;
    wire [3:0] wstrb;
    wire [1:0] bresp, rresp;
    wire awvalid, awready, wvalid, wready, bvalid, bready, arvalid, arready, rvalid, rready;
{wires}
    uart_axil_bridge #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_bridge (
        .clk(clk), .rst_n(rst_n), .rx(uart_rx), .tx(uart_tx),
        .awaddr(awaddr), .awvalid(awvalid), .awready(awready), .wdata(wdata), .wstrb(wstrb), .wvalid(wvalid), .wready(wready),
        .bresp(bresp), .bvalid(bvalid), .bready(bready), .araddr(araddr), .arvalid(arvalid), .arready(arready),
        .rdata(rdata), .rresp(rresp), .rvalid(rvalid), .rready(rready));
    {mod} u_regs (
        {conns});
    assign led = {led};
endmodule
`default_nettype wire
"""


class Board:
    def __init__(self, port):
        self.fd = os.open(port, os.O_RDWR | os.O_NOCTTY)
        a = termios.tcgetattr(self.fd)
        a[0] = a[1] = a[3] = 0
        a[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
        a[4] = a[5] = termios.B115200
        a[6][termios.VMIN] = 0
        a[6][termios.VTIME] = 0
        termios.tcsetattr(self.fd, termios.TCSANOW, a)
        time.sleep(0.2)
        termios.tcflush(self.fd, termios.TCIFLUSH)

    def _rd(self, n, t=1.0):
        b, end = b"", time.time() + t
        while len(b) < n and time.time() < end:
            if select.select([self.fd], [], [], 0.05)[0]:
                b += os.read(self.fd, 16)
        if len(b) != n:
            raise RuntimeError(f"board answered {len(b)} of {n} bytes: {b.hex()}")
        return b

    def read(self, addr):
        os.write(self.fd, b"R" + addr.to_bytes(4, "big"))
        b = self._rd(5)
        return "ERR slverr" if b[0] == 2 else ("OK 0x%08x" % int.from_bytes(b[1:], "big")) if b[0] == 0 else f"ERR resp{b[0]}"

    def write(self, addr, data):
        os.write(self.fd, b"W" + addr.to_bytes(4, "big") + data.to_bytes(4, "big"))
        b = self._rd(1)
        return "ERR slverr" if b[0] == 2 else "OK" if b[0] == 0 else f"ERR resp{b[0]}"

    def cmd(self, c):
        p = c.split()
        return self.read(int(p[1], 16)) if p[0] == "R" else self.write(int(p[1], 16), int(p[2], 16))


def emulate_reset(board, ir):
    base = int(ir["block"]["base_address"], 16)
    for r in ir["block"]["registers"]:
        if r["kind"] == "RW":
            rv = int(r.get("reset", "0x0"), 16) & 0xFFFFFFFF
            a = base + int(r["offset"], 16)
            if board.write(a, rv) != "OK" or board.read(a) != "OK 0x%08x" % rv:
                raise RuntimeError(f"could not restore {r['name']} to its reset value")


def run(ns):
    corpus = json.loads((ROOT / "tests/behavioral/scenarios.json").read_text())
    board = Board(ns.port)
    total = ok = bad = 0
    skipped: dict[str, int] = {}
    irs = {}
    for sc in corpus["scenarios"]:
        if sc["contract"] != ns.contract:
            continue
        if sc["contract"] not in irs:
            irs[sc["contract"]] = load_contract(str(ROOT / sc["contract"]))[0]
        ir = irs[sc["contract"]]
        emulate_reset(board, ir)
        skipped["emulated-reset"] = skipped.get("emulated-reset", 0) + 1
        for line, cs, expect, why in plan(ir, sc["ops"]):
            if line == "RESET":
                emulate_reset(board, ir)
                skipped["emulated-reset"] += 1
                continue
            if why and not isinstance(why, tuple):
                skipped[why] = skipped.get(why, 0) + 1
                continue
            got = [board.cmd(c) for c in cs][-1] if cs else None
            if isinstance(why, tuple):
                fdef = why[1]
                if got.startswith("OK 0x"):
                    got = "OK 0x%08x" % ((int(got[5:], 16) & _field_mask(fdef["lsb"], fdef["msb"])) >> fdef["lsb"])
            elif expect is None:
                skipped["driven-unjudged"] = skipped.get("driven-unjudged", 0) + 1
                continue
            total += 1
            if got == expect:
                ok += 1
                if ns.v:
                    print(f"  ok {sc['name']}: {line!r} -> {got}")
            else:
                bad += 1
                print(f"  MISMATCH {sc['name']}: {line!r}: model {expect}, board {got}")
    # directed: addresses with no register answer SLVERR and change nothing
    for cpath, ir in irs.items():
        base = int(ir["block"]["base_address"], 16)
        top = max(int(r["offset"], 16) for r in ir["block"]["registers"])
        for a in (base + top + 4, (base - 4) & 0xFFFFFFFF):
            for c in (f"W {a:08x} ffffffff", f"R {a:08x}"):
                total += 1
                g = board.cmd(c)
                if g == "ERR slverr":
                    ok += 1
                else:
                    bad += 1
                    print(f"  MISMATCH {cpath} directed {c!r}: wanted ERR slverr, board {g}")
    print(f"board_replay: compared {total}, equal {ok}, different {bad}; not compared: {skipped}")
    return 0 if bad == 0 and total else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("top"); t.add_argument("chw"); t.add_argument("contract")
    r = sub.add_parser("run"); r.add_argument("chw", nargs="?")
    r.add_argument("--port", default="/dev/ttyUSB1"); r.add_argument("--contract", default="examples/uart-contract/uart.chw"); r.add_argument("-v", action="store_true")
    ns = ap.parse_args()
    if ns.cmd == "top":
        sys.stdout.write(top_source(ns.chw, ns.contract))
    else:
        sys.exit(run(ns))

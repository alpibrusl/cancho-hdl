"""Roundtrip checks for the cancho-binding generator
(gen/cancho-binding/cancho_binding.py).

spec/generators/README.md §3 wants a `.cancho` file whose
accessors match the contract, carry stable-ID comments, and
whose DEVICE-owned DMA fields have no setter — "the type system
is what enforces this." The structural checks below pin every
landed palette rule:

1. Determinism (two runs byte-identical) and banner.
2. Module + foreign block declaration (`module <snake>`,
   `foreign block <Name> @ <hex> : u<bus_width>`).
3. Stable-ID comment on every register field, interrupt, and
   DMA field.
4. Accessor palette per register kind (§3, landed form):
   RW → getter + setter; RO → getter only; WO → setter only;
   W1C/W0C → `_clear()`; W1S/W0S → `_set()`.
5. Types: 1-bit → bool; enum → module-level `enum` declaration
   with labels verbatim; wider plain fields → u32.
6. Interrupt capability: `capability <PascalBlock><PascalIntr>`
   + arm/status/clear only when the corresponding linkage is
   declared.
7. DMA: DEVICE-owned fields get a getter and no setter (this is
   the §3.2 rule, the one the whole ownership model is built
   on); CPU-owned fields get both. Sizes land on
   u8/u16/u32/u64 via the c-header's size convention.
8. Refusal lane: a declared size with no u8/u16/u32/u64 mapping
   refuses with `generator-unimplemented` — from the binding
   generator AND, symmetrically, from the c-header (the two
   artifacts must refuse the same input together); two
   same-named enum fields with different label sets refuse.

Run from anywhere:
    python3 tests/roundtrip/cancho_binding_validates.py
"""

from __future__ import annotations

import importlib.util
import json
import pathlib
import re
import subprocess
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[2]

_HANDLERS = {
    "cancho_binding":
        (ROOT / "gen" / "cancho-binding" / "cancho_binding.py"),
    "c_header": (ROOT / "gen" / "c-header" / "c_header.py"),
}


def _load(name: str, path: pathlib.Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


FAILURES: list[str] = []


def expect(cond: bool, label: str, detail: str = "") -> None:
    if cond:
        print(f"  PASS  {label}")
    else:
        print(f"  FAIL  {label}")
        if detail:
            print(detail)
        FAILURES.append(label)


def main() -> int:
    print("== cancho-binding roundtrip ==")
    binding = _load("cb_gen_r", _HANDLERS["cancho_binding"])
    c_header = _load("c_header_mod_r", _HANDLERS["c_header"])
    from common import GeneratorUnimplemented  # noqa: E402

    sys.path.insert(0, str(ROOT / "tools" / "parse"))
    from parser import load_contract  # noqa: E402

    _snake = binding._snake
    _pascal = binding._pascal

    manifest = json.loads((ROOT / "examples" / "MANIFEST.json").read_text())

    for rel in manifest["valid"]:
        path = ROOT / rel
        ir, _ = load_contract(str(path))
        block = ir["block"]
        name = block["name"]
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
        bus_width = int(block.get("bus_width", 32))
        base = int(str(block["base_address"]), 16)

        src = binding.generate(ir, source_path=rel)
        src2 = binding.generate(ir, source_path=rel)

        print(f"-- {rel} --")
        expect(src == src2, "deterministic (two runs byte-identical)")
        expect(src.splitlines()[0] ==
               f"// Generated by cancho-hdl from {rel}. Do not edit.",
               "banner names source + Do not edit")
        expect(f"module {snake} {{" in src, f"module {snake} declared")
        expect(f"foreign block {name} @ 0x{base:X} : u{bus_width};" in src,
               "foreign block declaration with address and width")

        # Palette per field
        for reg in block["registers"]:
            kind = reg.get("kind", "RW")
            fields = reg.get("fields", []) or []
            for f in fields:
                fid = f"// chw:{name}.register.{reg['name']}.field.{f['name']}"
                expect(fid in src, f"stable ID for {reg['name']}.{f['name']}")
                visible = src[src.index(fid):] if fid in src else ""
                seg = src[src.index(fid): src.index(fid) + 400]
                is_enum = bool(f.get("enum"))
                width = f["msb"] - f["lsb"] + 1
                t = ("bool" if not is_enum and width == 1
                     else _pascal(f["name"]) if is_enum else "u32")
                fnames = [f"{_snake(reg['name'])}_{_snake(f['name'])}"] if not is_enum else [
                    f"{_snake(reg['name'])}_{_snake(f['name'])}_get"]
                if kind in ("RW",):
                    expected = [
                        f"fn {_snake(reg['name'])}_{_snake(f['name'])}_get() -> {t};"
                        if (is_enum or width > 1) else
                        f"fn {_snake(reg['name'])}_{_snake(f['name'])}() -> bool;",
                        f"fn {_snake(reg['name'])}_{_snake(f['name'])}_set(v: {t});"]
                elif kind in ("RO", "RC"):
                    expected = [
                        f"fn {_snake(reg['name'])}_{_snake(f['name'])}_get() -> {t};"
                        if (is_enum or width > 1) else
                        f"fn {_snake(reg['name'])}_{_snake(f['name'])}() -> bool;"]
                elif kind == "WO":
                    expected = [f"fn {_snake(reg['name'])}_{_snake(f['name'])}_set(v: {t});"]
                elif kind in ("W1C", "W0C"):
                    expected = [f"fn {_snake(reg['name'])}_{_snake(f['name'])}_clear();"]
                else:  # W1S / W0S
                    expected = [f"fn {_snake(reg['name'])}_{_snake(f['name'])}_set(v: {t});"]
                rest = seg[len(fid) + 1:seg.index("\n    //", 1) if "\n    //" in seg[1:] else len(seg)]
                for fn_line in expected:
                    expect(fn_line in seg, f"accessor {fn_line}", seg)

        # Interrupt capability group
        for intr in block.get("interrupts", []) or []:
            cap = _pascal(name) + _pascal(intr["name"])
            expect(f"capability {cap}" in src, f"capability {cap} present")
            iid = f"// chw:{name}.interrupt.{intr['name']}"
            expect(iid in src, f"stable ID comment for {intr['name']}")
            if "enable" in intr:
                expect(f"fn {_snake(intr['name'])}_arm();" in src,
                       f"arm accessor for {intr['name']}")
            if "status" in intr:
                expect(f"fn {_snake(intr['name'])}_status() -> bool;" in src,
                       f"status accessor for {intr['name']}")
            if "clear" in intr:
                expect(f"fn {_snake(intr['name'])}_clear();" in src,
                       f"clear accessor for {intr['name']}")

        # Enums landed at the bottom, verbatim labels
        seen: dict[str, list[str]] = {}
        for reg in block["registers"]:
            for f in reg.get("fields", []) or []:
                en = f.get("enum")
                if en and _pascal(f["name"]) not in seen:
                    seen[_pascal(f["name"])] = list(en.keys())
        for ename, labels in seen.items():
            expect(f"enum {ename} {{ {', '.join(labels)} }}" in src,
                   f"enum {ename} declared with labels verbatim")

        # DMA: owner rule + sizes
        for buf in ir.get("dma_buffers", []) or []:
            iid = f"    // chw:{name}.dma.{buf['name']}\n    buffer"
            expect(iid in src, f"stable ID comment for buffer {buf['name']}")
            starts = [m.start() for m in re.finditer(re.escape(iid), src)]
            s_index = starts[0]
            e_index = starts[1] if len(starts) > 1 else len(src)
            segment = src[s_index:e_index]
            for f in buf.get("fields", []) or []:
                owner = f.get("owner", "CPU")
                size = int(f.get("size", 4))
                t = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}[size]
                expect(f"fn {_snake(f['name'])}() -> {t};" in segment,
                       f"{buf['name']}.{f['name']} getter ({owner}-owned)")
                if owner == "DEVICE":
                    expect(f"fn {_snake(f['name'])}_set(v: {t});" not in segment,
                           f"{buf['name']}.{f['name']} has NO setter (DEVICE-owned)")
                else:
                    expect(f"fn {_snake(f['name'])}_set(v: {t});" in segment,
                           f"{buf['name']}.{f['name']} setter (CPU-owned)")

    print()
    print("## refusal lane ##")
    bad_size = {"version": "0.1.0",
                "block": {"name": "T", "base_address": "0x40000000", "bus_width": 32,
                          "endianness": "little", "registers": [
                              {"name": "A", "offset": "0x00", "kind": "RW", "fields": []}]},
                "dma_buffers": [{"name": "B", "fields": [
                    {"name": "p", "offset": "0x00", "owner": "CPU", "size": 3}]}]}
    try:
        binding.generate(bad_size, source_path="")
        expect(False, "size 3 refuses in the binding")
    except GeneratorUnimplemented:
        expect(True, "size 3 refuses with generator-unimplemented (binding)")
    try:
        c_header.generate(bad_size, source_path="")
        expect(False, "size 3 refuses in the c-header")
    except GeneratorUnimplemented:
        expect(True, "size 3 refuses with generator-unimplemented (c-header)")

    clash = {"version": "0.1.0",
             "block": {"name": "T", "base_address": "0x40000000", "bus_width": 32,
                       "endianness": "little", "registers": [
                           {"name": "A", "offset": "0x00", "kind": "RW", "fields": [
                               {"name": "M", "lsb": 0, "msb": 1, "enum": {"Off": 0}}]},
                           {"name": "B", "offset": "0x04", "kind": "RW", "fields": [
                               {"name": "M", "lsb": 0, "msb": 1, "enum": {"Off": 0, "On": 1}}]}]},
             "dma_buffers": []}
    try:
        binding.generate(clash, source_path="")
        expect(False, "enum-name clash refuses")
    except GeneratorUnimplemented:
        expect(True, "same-name enums with different labels refuse (no type collision)")

    dispatcher = subprocess.run(
        [sys.executable, "tools/generate/generate.py", "--target", "cancho-binding",
         "examples/refusal/field-overlap.chw"], capture_output=True, text=True, cwd=str(ROOT))
    expect(dispatcher.returncode == 1 and "field-overlap" in dispatcher.stderr,
           "dispatcher refuses a checker-refused contract (exit 1)")
    svd = subprocess.run(
        [sys.executable, "tools/generate/generate.py", "--target", "svd",
         "examples/uart-contract/uart.chw"], capture_output=True, text=True, cwd=str(ROOT))
    expect(svd.returncode == 0 and svd.stdout.startswith("<?xml"),
           "svd (landed in Phase 2) generates from the valid example — "
           "the stub period of generator-unimplemented is over; "
           "tests/roundtrip/svd_validates.py pins its contract")

    print()
    if FAILURES:
        print(f"== cancho-binding roundtrip: {len(FAILURES)} failure(s) ==")
        return 1
    print("== cancho-binding roundtrip: all pass ==")
    return 0


if __name__ == "__main__":
    sys.exit(main())

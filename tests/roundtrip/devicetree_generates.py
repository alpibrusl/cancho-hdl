"""Roundtrip checks for the devicetree generator (gen/devicetree).

For every valid example in `examples/MANIFEST.json#valid`:

1. Determinism: two runs over the same IR are byte-identical
   (spec/generators/README.md §1 rule 2).
2. Banner: the first line names the source, "Do not edit."
3. Node shape: `<label> <snake>@<unit>` where unit is the base
   address in hex, no `0x` (DTS unit-address rule); label and
   snake are the same snake-casing of the block name.
4. The stable ID is present as a comment (`chw:<block>`), and
   `compatible = "cancho,<dash>-v<major>"`.
5. `reg` matches §4.2's formula recomputed independently from the
   IR: base, then highest register offset + bus_width/8.
6. Every declared interrupt appears, in declaration order, with
   its stable-ID comment and IRQ number.
7. A block without interrupts emits no interrupt lines (the
   interrupt-parent/interrupts properties are conditional).

Plus the refusal lane: an empty register map (`reg` undefined)
and a base address beyond one 32-bit address cell are refused
with `generator-unimplemented` — by direct raise from the
generator and by exit code 1 from the dispatcher.

If `dtc` is on `$PATH`, each fragment is additionally parsed with
it (spec §4.2 "validates against the upstream DTS schema"); the
structural checks above are what run everywhere.

Run from anywhere:
    python3 tests/roundtrip/devicetree_generates.py
"""

from __future__ import annotations

import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "gen"))
sys.path.insert(0, str(ROOT / "tools" / "parse"))

from common import GeneratorUnimplemented  # noqa: E402
from parser import load_contract  # noqa: E402

# gen/devicetree is a directory that would shadow the module name
# under a plain sys.path import, so the generator loads by spec —
# exactly as the manifest dispatcher does.
_spec = importlib.util.spec_from_file_location(
    "cancho_hdl_gen_devicetree", ROOT / "gen" / "devicetree" / "devicetree.py")
_devicetree_mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_devicetree_mod)
generate = _devicetree_mod.generate
_snake = _devicetree_mod._snake

FAILURES: list[str] = []


def expect(cond: bool, label: str, detail: str = "") -> None:
    if cond:
        print(f"  PASS  {label}")
    else:
        print(f"  FAIL  {label}")
        if detail:
            print(detail)
        FAILURES.append(label)


def load_module(path: str, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    print("== devicetree roundtrip ==")

    manifest = json.loads((ROOT / "examples" / "MANIFEST.json").read_text())
    for rel in manifest["valid"]:
        path = ROOT / rel
        ir, _ = load_contract(str(path))
        block = ir["block"]
        name = block["name"]
        snake = _snake(name)
        base = int(str(block["base_address"]), 16)
        bus_width = int(block.get("bus_width", 32))
        registers = block["registers"]
        max_off = max(int(str(r["offset"]), 16) for r in registers)
        range_size = max_off + bus_width // 8
        major = str(ir.get("version", "0.1.0")).split(".")[0]

        src = generate(ir, source_path=rel)
        src2 = generate(ir, source_path=rel)
        lines = src.splitlines()

        print(f"-- {rel} --")
        expect(src == src2, "deterministic (two runs byte-identical)")
        expect(lines[0] == f"/* Generated by cancho-hdl from {rel}. Do not edit. */",
               "banner names the source and says Do not edit", lines[0])
        expect(f"{snake}: {snake}@{base:X} {{" in src,
               f"node {snake}@{base:X} with label", src.split('\n')[1])
        expect(f"/* chw:{name} */" in src, "stable ID comment present")
        expect(f'compatible = "cancho,{snake.replace("_", "-")}-v{major}";' in src,
               "compatible pins block + version major",
               [l for l in lines if "compatible" in l][0])
        expect(f"reg = <0x{base:X} 0x{range_size:X}>;" in src,
               "reg is §4.2's address range (base, max offset + width/8)",
               [l for l in lines if "reg = " in l][0])

        interrupts = block.get("interrupts", []) or []
        if interrupts:
            expect("interrupt-parent = <&intc>;" in src, "interrupt-parent present")
            nums = [str(i["number"]) for i in interrupts]
            int_line = [l for l in lines if l.strip().startswith("interrupts = ")][0]
            expect(all(f"<{n} 4>" in int_line for n in nums),
                   "every interrupt number in the property", int_line)
            for i in interrupts:
                cid = f"chw:{name}.interrupt.{i['name']}, IRQ {i['number']}"
                expect(cid in src, f"stable-ID comment for interrupt {i['name']}", cid)
            # declaration order: comment blocks appear in order
            idx = [src.index(f"chw:{name}.interrupt.{i['name']}") for i in interrupts]
            expect(idx == sorted(idx), "interrupt comments in declaration order")
        else:
            expect("interrupt" not in src, "no interrupt lines when none declared")

    # dtc parse (when available)
    dtc = shutil.which("dtc")
    if dtc:
        import tempfile
        for rel in manifest["valid"]:
            ir, _ = load_contract(str(ROOT / rel))
            src = generate(ir, source_path=rel)
            with tempfile.NamedTemporaryFile(suffix=".dts", mode="w") as fh:
                fh.write(src)
                fh.flush()
                proc = subprocess.run([dtc, "-I", "dts", "-O", "dtb", "-q", fh.name],
                                      capture_output=True, text=True)
                expect(proc.returncode == 0, f"{rel}: dtc parses the fragment",
                       proc.stderr[:400])
    else:
        print("  NOTE  dtc not on $PATH; structural checks only (spec §4.2 parse check skipped)")

    print()
    print("## refusal lane ##")
    zero = {"version": "0.1.0", "block": {"name": "T", "base_address": "0x40000000",
            "bus_width": 32, "endianness": "little", "registers": []}, "dma_buffers": []}
    try:
        generate(zero, source_path="")
        expect(False, "zero registers refuse")
    except GeneratorUnimplemented:
        expect(True, "zero registers refuse with generator-unimplemented")
    wide = {"version": "0.1.0", "block": {"name": "T", "base_address": "0x1_0000_0000",
            "bus_width": 32, "endianness": "little", "registers": [
                {"name": "A", "offset": "0x00", "kind": "RW", "fields": []}]},
            "dma_buffers": []}
    try:
        generate(wide, source_path="")
        expect(False, ">32-bit base refuses")
    except GeneratorUnimplemented:
        expect(True, ">32-bit base refuses with generator-unimplemented")

    # Class identity: even via the dispatcher's dynamic module load,
    # the refusal is the same object as tests import (sys.modules
    # caching on `common`), so dispatcher-side catches cannot miss.
    proc = subprocess.run(
        [sys.executable, "tools/generate/generate.py", "--target", "devicetree",
         "examples/refusal/field-overlap.chw"], capture_output=True, text=True, cwd=str(ROOT))
    expect(proc.returncode == 1 and "field-overlap" in proc.stderr,
           "dispatcher refuses a checker-refused contract (exit 1)")

    print()
    if FAILURES:
        print(f"== devicetree roundtrip: {len(FAILURES)} failure(s) ==")
        return 1
    print("== devicetree roundtrip: all pass ==")
    return 0


if __name__ == "__main__":
    sys.exit(main())

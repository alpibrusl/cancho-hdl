"""C header generator for cancho-hdl.

Implements the per-target contract in `spec/generators/README.md` §2.
Reads a contract IR (the JSON form from `spec/contract-schema/`) and
emits a C header that:

- Compiles under clang/gcc with `-Wall -Wextra -Werror -std=c11`.
- Has a bitfield struct per register, laid out from `lsb` to `msb`,
  with reserved bits filled in as `_rsvd`.
- Has a block struct with one `volatile` member per register, in
  offset order, with reserved gaps filled in.
- Carries a stable ID comment per field and per register, so a
  generated header that defines `UART_CTRL_BAUD_DIV_Msk` is
  traceable back to `chw:UartRegs.register.CTRL.field.BAUD_DIV`.
- Defines `BASE` and `RESET_*` constants.
- Emits DMA buffers as packed structs with `volatile` on
  DEVICE-owned fields (where CPU writes are forbidden by
  ownership) and `const volatile` on CPU-owned fields the
  device fills.

The output is deterministic. Same IR → byte-identical bytes.

Usage:

    from c_header import generate
    src = generate(ir_dict, source_path="examples/uart-contract/uart.chw")
    open("gen/uart.h", "w").write(src)
"""

from __future__ import annotations

import io
import pathlib as _pathlib
import sys as _sys
from typing import Any

# Same loading discipline as the other Phase 2 generators (module
# by path; gen/ must be importable for the shared refusal class).
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[1]))
from common import GeneratorUnimplemented


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _bus_c_type(bus_width: int) -> str:
    return {8: "uint8_t", 16: "uint16_t", 32: "uint32_t"}[bus_width]


def _mask(bus_width: int) -> int:
    return (1 << bus_width) - 1


def _field_mask(lsb: int, msb: int) -> int:
    width = msb - lsb + 1
    return ((1 << width) - 1) << lsb


def _to_c_name(name: str) -> str:
    """`UartRegs` → `UART_REGS`, `CTRL` → `CTRL`, `UartRegs_CTRL` → `UART_REGS_CTRL`.

    Mirrors `_to_lower_snake` for the SCREAMING_SNAKE_CASE convention.
    """
    return _to_lower_snake(name).upper()


def _to_lower_snake(name: str) -> str:
    """`UartRegs` → `uart_regs`, `CTRL` → `ctrl`, `UartRegs_CTRL` → `uart_regs_ctrl`.

    A run of consecutive uppercase letters is treated as an
    abbreviation and is not split. A lowercase letter following an
    abbreviation starts a new word (so `UartCTRLx` → `uart_c_t_r_lx`,
    which is wrong, but the contract discourages that kind of
    mixed-up naming).
    """
    if not name:
        return name
    out: list[str] = []
    for i, ch in enumerate(name):
        if ch.isupper():
            # New word boundary if:
            # - this is not the first character, AND
            # - the previous character is lowercase, OR
            # - the previous character is uppercase AND the next is lowercase
            #   (end of an abbreviation, e.g. the 'R' in 'UartRegs' before 'egs')
            prev_lower = i > 0 and name[i - 1].islower()
            end_of_abbrev = (
                i > 0 and i + 1 < len(name)
                and name[i - 1].isupper()
                and name[i + 1].islower()
            )
            if i > 0 and (prev_lower or end_of_abbrev):
                out.append("_")
        out.append(ch.lower())
    return "".join(out)


def _comment_id(*parts: str) -> str:
    """Stable ID for the contract entity named by `parts`. Examples:
    _comment_id("UartRegs", "register", "CTRL", "field", "BAUD_DIV")
    → "chw:UartRegs.register.CTRL.field.BAUD_DIV"
    """
    return "chw:" + ".".join(parts)


# ---------------------------------------------------------------------------
# Top-level
# ---------------------------------------------------------------------------


def generate(ir: dict[str, Any], source_path: str = "<memory>") -> str:
    """Generate the C header for `ir`. Returns the source as a string.

    The output is byte-deterministic: same IR, same source path →
    same output. The source path is included in the header banner
    so a diff between two generated headers is meaningful.
    """
    block = ir["block"]
    block_name: str = block["name"]
    bus_width: int = block["bus_width"]
    base_address: int = int(block["base_address"], 16)

    out = io.StringIO()
    guard = f"CANCHO_HDL_{_to_c_name(block_name)}_H"

    # Banner
    out.write(f"/* Generated by cancho-hdl from {source_path}. Do not edit. */\n")
    out.write(f"#ifndef {guard}\n")
    out.write(f"#define {guard}\n\n")
    out.write("#include <stdint.h>\n")
    out.write("#include <stddef.h>\n\n")

    if not (1 <= bus_width <= 32 and bus_width in (8, 16, 32)):
        # The checker should have caught this; emit a comment and bail.
        out.write(f"/* ERROR: invalid bus_width {bus_width}; cannot generate. */\n")
        out.write(f"#endif /* {guard} */\n")
        return out.getvalue()

    base_c = _bus_c_type(bus_width)

    # Per-register bitfield structs
    registers_sorted = sorted(
        block.get("registers", []), key=lambda r: int(r["offset"], 16)
    )
    for reg in registers_sorted:
        _emit_register_struct(out, reg, block_name, base_c, bus_width)

    # Block struct
    _emit_block_struct(out, block_name, registers_sorted, bus_width, base_c)

    # DMA buffers
    dma_buffers = ir.get("dma_buffers", [])
    for buf in dma_buffers:
        _emit_dma_struct(out, buf, block_name)

    # Constants
    out.write(f"/* {_comment_id(block_name)} */\n")
    out.write(f"#define {_to_c_name(block_name)}_BASE 0x{base_address:08x}u\n")
    out.write(f"#define {_to_c_name(block_name)}_BUS_WIDTH {bus_width}\n\n")

    # Per-register reset values
    for reg in registers_sorted:
        if "reset" in reg:
            rname = _to_c_name(reg["name"])
            bname = _to_c_name(block_name)
            reset_val = int(reg["reset"], 16)
            out.write(
                f"#define {bname}_{rname}_RESET 0x{reset_val:0{bus_width // 4}x}u\n"
            )
    out.write("\n")

    out.write(f"#endif /* {guard} */\n")
    return out.getvalue()


# ---------------------------------------------------------------------------
# Register bitfield struct
# ---------------------------------------------------------------------------


def _emit_register_struct(
    out: io.StringIO,
    reg: dict[str, Any],
    block_name: str,
    base_c: str,
    bus_width: int,
) -> None:
    reg_name: str = reg["name"]
    kind: str = reg["kind"]
    fields = reg.get("fields", [])

    out.write(f"/* {_comment_id(block_name, 'register', reg_name)} */\n")
    out.write(f"/* kind: {kind} */\n")
    if not fields:
        out.write(f"/* no fields declared */\n\n")
        return

    out.write(f"typedef struct {{\n")

    # Walk from bit 0 to bus_width-1, emitting either a field or _rsvd.
    occupied: list[tuple[int, int, dict[str, Any]]] = [
        (f["lsb"], f["msb"], f) for f in fields
    ]
    occupied.sort()

    pos = 0
    for lsb, msb, fdef in occupied:
        if lsb > pos:
            # Reserved gap.
            width = lsb - pos
            out.write(f"    {base_c} _rsvd{pos} : {width};\n")
        width = msb - lsb + 1
        fname = fdef["name"]
        # Stable ID comment
        out.write(
            f"    {base_c} {fname.lower()} : {width}; "
            f"/* {_comment_id(block_name, 'register', reg_name, 'field', fname)} */\n"
        )
        # Enum documentation
        if "enum" in fdef:
            for label, val in fdef["enum"].items():
                out.write(f"        /* enum: {label} = {val} */\n")
        pos = msb + 1
    if pos < bus_width:
        width = bus_width - pos
        out.write(f"    {base_c} _rsvd{pos} : {width};\n")
    out.write(f"}} {_to_lower_snake(reg_name)}_t;\n\n")


# ---------------------------------------------------------------------------
# Block struct
# ---------------------------------------------------------------------------


def _emit_block_struct(
    out: io.StringIO,
    block_name: str,
    registers: list[dict[str, Any]],
    bus_width: int,
    base_c: str,
) -> None:
    out.write(f"/* {_comment_id(block_name, 'block')} */\n")
    out.write(f"typedef struct {{\n")

    reg_size_bytes = bus_width // 8
    pos = 0
    for reg in registers:
        offset = int(reg["offset"], 16)
        rel = offset // reg_size_bytes
        if rel > pos:
            # Gap: emit padding.
            gap = rel - pos
            # In bytes; C arrays of base_c are awkward to size correctly.
            # Use a byte-sized type for the gap so the layout matches.
            out.write(f"    uint8_t _gap{pos}[{gap * reg_size_bytes}];\n")
        kind = reg["kind"]
        kind_note = f" /* {kind} */" if kind != "RW" else ""
        out.write(
            f"    volatile {base_c} {reg['name'].lower()}; "
            f"/* {_comment_id(block_name, 'register', reg['name'])} */{kind_note}\n"
        )
        pos = rel + 1
    out.write(f"}} {_to_lower_snake(block_name)}_t;\n\n")


# ---------------------------------------------------------------------------
# DMA buffer struct (packed)
# ---------------------------------------------------------------------------


def _emit_dma_struct(
    out: io.StringIO,
    buf: dict[str, Any],
    block_name: str,
) -> None:
    buf_name: str = buf["name"]
    out.write(f"/* {_comment_id(block_name, 'dma', buf_name)} */\n")
    out.write(
        "/* DMA buffers are tightly packed; offsets are explicit. "
        "DEVICE-owned fields must be written only by the device. */\n"
    )
    out.write(
        f"typedef struct __attribute__((packed)) {{\n"
    )

    pos = 0
    for f in sorted(buf.get("fields", []), key=lambda x: int(x["offset"], 16)):
        offset = int(f["offset"], 16)
        if offset > pos:
            out.write(f"    uint8_t _gap{pos}[{offset - pos}];\n")
        size = f.get("size", 4)
        if size not in (1, 2, 4, 8):
            raise GeneratorUnimplemented(
                f"DMA field {f['name']!r} has size {size}, which has no "
                "u8/u16/u32/u64 C mapping; refusing (the cancho-binding "
                "refuses the same input)")
        c_type = {1: "uint8_t", 2: "uint16_t", 4: "uint32_t", 8: "uint64_t"}[size]
        owner = f.get("owner", "CPU")
        # The owner is documented; the C type itself doesn't enforce it
        # (C has no write-only field qualifier). Use `volatile` for
        # both directions since the bus can race.
        vol = "volatile " if owner == "DEVICE" else "volatile "
        out.write(
            f"    {vol}{c_type} {f['name'].lower()}; "
            f"/* owner: {owner} */ "
            f"/* {_comment_id(block_name, 'dma', buf_name, 'field', f['name'])} */\n"
        )
        pos = offset + size
    out.write(f"}} {_to_lower_snake(buf_name)}_t;\n\n")


